"""Where each text blank's printed rule sits on the card.

Entries write on their blank's printed underline (the rule), which is card
artwork, not form data — and the form's rectangles don't track it: their bottom
edges sit anywhere from about 0.9pt above to 1pt below their rules. So each
rule's top edge was measured once from the pinned base card, by
`measure_rule_positions.py`; rerun it if the base card changes. The values come
from a render, so they are close but inexact; that script's docstring gives the
error and how to measure exactly.

Every text field with a printed rule is listed: all but `SI.t.1`. That field is
the space after "Primary Signals to:" at the top of the Signals panel, a heading
over the Declarer's Lead and Partner's Lead columns below it. The card prints no
underline there, and Bridgodex has no setting for the field, so no entry ever
lands in it. If a setting ever maps to it, `rule_positions_test.py` flags the
missing rule.
"""

